"""Regenerates the wiki pages that mirror the code:
  docs/guide/config.md  from the Config.Bind calls in src/Greenlings/Plugin.cs
  docs/dev/tests.md     from the leading comments of tests/*.txt

Run from the repo root:  python scripts/gen-docs.py
The Pages workflow runs it before building, so the published pages always match the code.
"""
import re
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "src/Greenlings/Plugin.cs").read_text(encoding="utf-8")
out = root / "docs/guide/config.md"

bind = re.compile(
    r'Config\.Bind\(\s*"([^"]+)",\s*"([^"]+)",\s*(.+?),\s*"((?:[^"\\]|\\.)*)"\s*\)',
    re.S,
)


def default(raw: str) -> str:
    raw = " ".join(raw.split())
    if raw.startswith('"') and raw.endswith('"'):
        raw = raw[1:-1]
        return ", ".join(raw.split(",")) if raw else "*(empty)*"
    m = re.fullmatch(r"new Color\(([^)]*)\)", raw)
    if m:
        return "RGB " + m.group(1).replace("f", "")
    return re.sub(r"(?<=\d)f\b", "", raw)


sections: dict[str, list[tuple[str, str, str]]] = {}
for sec, key, dflt, desc in bind.findall(src):
    sections.setdefault(sec, []).append((key, default(dflt), desc.replace("|", "\\|")))

lines = [
    "# Configuration",
    "",
    "<!-- Generated by scripts/gen-docs.py from src/Greenlings/Plugin.cs. Don't edit by hand. -->",
    "",
    "All settings live in `BepInEx/config/greenlings.cfg`, which is created on first launch.",
    "Most take effect immediately. The taming items (`[Taming] Item`, `BruteItems`), `TamedTint` and `NestScale` need a restart.",
    "",
    "!!! warning \"Multiplayer\"",
    "    Config isn't server-synced yet, so keep everyone's file the same. Server sync is on the [roadmap](../project/roadmap.md).",
    "",
]
for sec, rows in sections.items():
    lines += [f"## {sec}", "", "| Setting | Default | What it does |", "|---|---|---|"]
    lines += [f"| `{k}` | {d} | {t} |" for k, d, t in rows]
    lines.append("")

out.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {out.relative_to(root)}: {sum(len(r) for r in sections.values())} settings in {len(sections)} sections")

# ---- scenario tests ----------------------------------------------------------------------

scenarios, shared = [], []
for f in sorted((root / "tests").glob("*.txt")):
    about = []
    for line in f.read_text(encoding="utf-8").splitlines():
        if not line.startswith("#"):
            break
        about.append(line.lstrip("# ").strip())
    row = f"| `{f.stem}` | {' '.join(about).replace('|', chr(92) + '|') or '*(no description)*'} |"
    (shared if f.stem.startswith("_") else scenarios).append(row)

tests_out = root / "docs/dev/tests.md"
tests_out.parent.mkdir(parents=True, exist_ok=True)
tests_out.write_text("\n".join([
    "# Scenario tests",
    "",
    "<!-- Generated by scripts/gen-docs.py from tests/*.txt. Don't edit by hand. -->",
    "",
    "Each file in `tests/` is a script the dev harness plays against the running game, checking the",
    "`[GLEVT]` log as it goes (see [Dev loop and harness](harness.md)). The description is the comment at the top of the file.",
    "",
    "```powershell",
    "./scripts/dev.ps1 test                         # run them all",
    "./scripts/dev.ps1 test tests/teach-haul.txt    # just one",
    "```",
    "",
    f"## Scenarios ({len(scenarios)})",
    "",
    "| Test | What it checks |",
    "|---|---|",
    *scenarios,
    "",
    "`persist-1` and `persist-2` are run around a game restart: `dev.ps1 test tests/persist-1.txt; dev.ps1 run; dev.ps1 test tests/persist-2.txt`.",
    "",
    "## Shared preambles",
    "",
    "Pulled into scenarios with `!include`.",
    "",
    "| File | Does |",
    "|---|---|",
    *shared,
    "",
]), encoding="utf-8")
print(f"wrote {tests_out.relative_to(root)}: {len(scenarios)} scenarios")
